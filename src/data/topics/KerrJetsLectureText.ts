export const getFormulaExplanation = (term: FormulaTerm, v: LectureValues): string => {
  switch (term) {
    case 'gtphi':
      return 'Недиагональный член метрики g_tφ заставляет любую падающую частицу и силовую линию магнитного поля вращаться в сторону спина чёрной дыры.';
    case 'ergo':
      return `При текущем спине a* = ${v.spinA.toFixed(2)} горизонт сжался до ${v.rPlus.toFixed(2)} r_s, открыв между ${v.rPlus.toFixed(2)} r_s и 1.00 r_s рабочую зону эргосферы.`;
    case 'bz_power':
      return `Мощность выброса квадратично зависит от спина a* и поля B. Если a* = 0 (Шварцшильд) или B = 0, джет мгновенно гаснет (сейчас P_BZ = ${v.jetPower}%).`;
  }
};

